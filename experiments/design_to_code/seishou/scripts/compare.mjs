import pixelmatch from 'pixelmatch';
import { PNG } from 'pngjs';
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';

const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'..');
const out=path.join(root,'evidence','iteration_02');
const masterPath=process.env.SEISHOU_MASTER_PATH;
if(!masterPath||!fs.existsSync(masterPath)) throw new Error('SEISHOU_MASTER_PATH must point to the exact Library Seishou_PC_Master_v1.png');
const masterSha=crypto.createHash('sha256').update(fs.readFileSync(masterPath)).digest('hex');
const expectedMasterSha='cc879352445655f84f460dd41b9267d34bd1eafc3b984486b4b09e6d9c4a1bbc';
if(masterSha!==expectedMasterSha) throw new Error(`Master SHA mismatch: ${masterSha}`);
fs.mkdirSync(out,{recursive:true});
const expectedPath=path.join(out,'expected_exact.png');
await sharp(masterPath).extract({left:0,top:0,width:786,height:428}).png({compressionLevel:9}).toFile(expectedPath);
const actualPath=path.join(out,'actual_786.png');
const expected=PNG.sync.read(fs.readFileSync(expectedPath));
const actual=PNG.sync.read(fs.readFileSync(actualPath));
if(expected.width!==actual.width||expected.height!==actual.height)throw new Error(`dimension mismatch expected ${expected.width}x${expected.height}, actual ${actual.width}x${actual.height}`);
const diff=new PNG({width:actual.width,height:actual.height});
const threshold=.10;
const mismatchPixels=pixelmatch(expected.data,actual.data,diff.data,actual.width,actual.height,{threshold,includeAA:false});
fs.writeFileSync(path.join(out,'diff_exact.png'),PNG.sync.write(diff));
await sharp({create:{width:1572,height:428,channels:3,background:'#ffffff'}}).composite([{input:await sharp(expectedPath).png().toBuffer(),left:0,top:0},{input:await sharp(actualPath).png().toBuffer(),left:786,top:0}]).jpeg({quality:92}).toFile(path.join(out,'expected_vs_actual_786.jpg'));
const capture=JSON.parse(fs.readFileSync(path.join(out,'capture.json'),'utf8'));
const heroManifest=JSON.parse(fs.readFileSync(path.join(root,'reference','hero_asset_manifest_v2.json'),'utf8'));
const total=actual.width*actual.height;
const report={schema:'issue139_seishou_header_hero_trust_diff_v2',masterLibraryPath:'/LP制作事業/Design-to-Code/Seishou/Seishou_PC_Master_v1.png',masterSha256:masterSha,expected:{kind:'exact_lossless_master_crop',width:786,height:428,rawRgbSha256:heroManifest.exact_expected.crop_raw_rgb_sha256},threshold,mismatchPixels,mismatchRatio:mismatchPixels/total,viewport:{width:786,height:428},productionViewport:capture.productionViewport,cleanHero:heroManifest.clean_hero,before:{iteration:'01',artifactId:10964151830,mismatchPixels:123662,mismatchRatio:0.3675953009440917,note:'v1 used compressed proxy Expected and low-resolution Master-derived Hero; retained only as historical comparison.'},scope:'Header + Hero + Trust strip v2 only; no next section.',interpretation:'Exact Master crop is the Expected. Mismatch ratio remains diagnostic; AI-rendered Master glyph pixels are not clean-DOM typography targets.'};
fs.writeFileSync(path.join(out,'comparison_exact.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
